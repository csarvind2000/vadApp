"""
ATA-HS: Adaptive Temporal Attention with Hybrid Scoring.

The proposed method. Two contributions, each mapped to a thesis objective.

Objective 2 -- Adaptive Temporal Attention (ATA)
    * Multi-scale dilated temporal convolutions give every snippet short- and
      long-range motion context before attention.
    * Sparse attention via alpha-entmax. Unlike softmax (never exactly zero) and
      unlike hard top-k (not differentiable -- the defect that silently disabled
      the selector in the earlier Ped2 prototype), entmax produces *exactly*
      sparse weights with a well-defined gradient. Irrelevant snippets get
      weight 0 and receive no gradient, but the selection itself is learned.
    * Adaptive budget. A gating head predicts, per video, how peaked the
      attention should be; a budget regulariser penalises spending attention
      mass broadly. Long uneventful stretches collapse to a few active snippets
      while anomalous bursts stay wide. Existing sparse-attention VAD work fixes
      the sparsity level as a hyperparameter; making it input-conditioned is the
      novel claim, and `--fixed_alpha` is the ablation that tests it.

Objective 3 -- Hybrid Scoring (HS)
    Three complementary signals, fused with input-dependent weights:
      s_mil  supervised MIL score        (what the weak labels teach)
      s_mag  deviation from the normal   (one-class signal, needs no labels;
             feature centre                RTFM shows magnitude separates well)
      s_tmp  temporal prediction error   (catches abrupt transitions MIL misses)
    A gating network emits per-snippet mixing weights, so the model can rely on
    different evidence in different videos. Fixed equal weights are the ablation.

Everything here is deliberately ablatable: each component can be switched off
from the constructor so the ablation table is generated by the same code path
that produces the headline number.
"""
from __future__ import annotations

from typing import Dict, Optional, Tuple

import torch
import torch.nn as nn
import torch.nn.functional as F


# ---------------------------------------------------------------------------
# Sparse attention
# ---------------------------------------------------------------------------
# Finite stand-in for -inf when masking padded snippets. entmax squares the
# sorted logits and takes cumulative sums, so a true -inf produces inf - inf = NaN
# in the variance term. Large-but-finite masks out just as effectively.
NEG_MASK = -1e4
_EPS = 1e-12


def entmax15(x: torch.Tensor, dim: int = -1) -> torch.Tensor:
    """
    Exact alpha-entmax with alpha = 1.5 (Peters, Niculae & Martins, ACL 2019).

    Returns a distribution that is *exactly* sparse: entries below a learned
    threshold become precisely zero, unlike softmax. Fully differentiable, so the
    selection is trained by the task loss.

    Note on stability: delta is clamped to a small POSITIVE epsilon rather than 0
    before the square root. d/dx sqrt(x) is infinite at x = 0, so clamping to
    exactly 0 makes the forward pass look fine while poisoning the backward pass
    with NaN the moment any coordinate sits on the support boundary.
    """
    x = x / 2.0
    x_sorted, _ = torch.sort(x, descending=True, dim=dim)
    rho = torch.arange(1, x.size(dim) + 1, device=x.device, dtype=x.dtype)
    shape = [1] * x.dim()
    shape[dim] = -1
    rho = rho.view(shape)

    mean = x_sorted.cumsum(dim) / rho
    mean_sq = (x_sorted ** 2).cumsum(dim) / rho
    ss = rho * (mean_sq - mean ** 2)
    delta = torch.clamp((1 - ss) / rho, min=_EPS)   # positive: sqrt'(0) is inf
    tau = mean - torch.sqrt(delta)

    support = (tau <= x_sorted).sum(dim=dim, keepdim=True).clamp(min=1)
    tau_star = tau.gather(dim, support - 1)
    return torch.clamp(x - tau_star, min=0) ** 2


def sparsemax(x: torch.Tensor, dim: int = -1) -> torch.Tensor:
    """alpha-entmax with alpha = 2 (Martins & Astudillo, 2016). Sparser than entmax15."""
    x_sorted, _ = torch.sort(x, descending=True, dim=dim)
    rho = torch.arange(1, x.size(dim) + 1, device=x.device, dtype=x.dtype)
    shape = [1] * x.dim()
    shape[dim] = -1
    rho = rho.view(shape)
    cumsum = x_sorted.cumsum(dim) - 1
    support = (rho * x_sorted > cumsum).sum(dim=dim, keepdim=True).clamp(min=1)
    tau = cumsum.gather(dim, support - 1) / support.to(x.dtype)
    return torch.clamp(x - tau, min=0)


def hard_topk(x: torch.Tensor, dim: int = -1, k: int = 16) -> torch.Tensor:
    """
    Non-differentiable top-K selection, included as a control.

    Retains the k largest scores and zeros the rest, renormalising to sum to one.
    The selection itself carries no gradient: the returned weights are a function
    of which entries were chosen, and that choice is piecewise constant in the
    scores. A selector trained only through this receives no learning signal,
    which is the behaviour entmax is introduced to avoid.
    """
    kk = min(k, x.shape[dim])
    thresh = x.topk(kk, dim=dim).values.narrow(dim, kk - 1, 1)
    keep = (x >= thresh).to(x.dtype)
    w = keep / keep.sum(dim=dim, keepdim=True).clamp(min=1)
    return w


ATTN_FNS = {
    "entmax": entmax15,
    "sparsemax": sparsemax,
    "softmax": lambda x, dim=-1: torch.softmax(x, dim=dim),
    "topk": hard_topk,
}


# ---------------------------------------------------------------------------
# Multi-scale temporal context
# ---------------------------------------------------------------------------
class MultiScaleTemporal(nn.Module):
    """
    Parallel dilated 1-D convolutions over the snippet axis.

    Dilations 1/2/4/8 at kernel size 3 give receptive fields of 3/5/9/17
    snippets, i.e. roughly 1.6 s to 9 s at 16-frame snippets and 30 fps -- the
    range over which the anomalies in UCF-Crime actually unfold.
    """

    def __init__(self, d_model: int, dilations=(1, 2, 4, 8), dropout: float = 0.1):
        super().__init__()
        assert d_model % len(dilations) == 0, "d_model must divide evenly across dilations"
        branch = d_model // len(dilations)
        self.branches = nn.ModuleList([
            nn.Conv1d(d_model, branch, kernel_size=3, padding=d, dilation=d)
            for d in dilations
        ])
        self.norm = nn.LayerNorm(d_model)
        self.drop = nn.Dropout(dropout)

    def forward(self, x: torch.Tensor, mask: Optional[torch.Tensor] = None) -> torch.Tensor:
        """x: [B,T,D] -> [B,T,D] (residual)."""
        h = x.transpose(1, 2)                                  # [B,D,T]
        if mask is not None:
            h = h * mask.unsqueeze(1).to(h.dtype)              # zero the padding
        h = torch.cat([F.relu(b(h)) for b in self.branches], dim=1)
        h = h.transpose(1, 2)                                  # [B,T,D]
        if mask is not None:
            # A dilated kernel straddling the padding boundary mixes zeros into
            # real positions; zeroing again keeps padded slots from propagating.
            h = h * mask.unsqueeze(-1).to(h.dtype)
        return self.norm(x + self.drop(h))


# ---------------------------------------------------------------------------
# Adaptive sparse temporal attention
# ---------------------------------------------------------------------------
class AdaptiveTemporalAttention(nn.Module):
    """
    Sparse attention over the temporal axis with an input-conditioned budget.

    A gate reads the video's global context and predicts a temperature. Low
    temperature concentrates attention on a few snippets; high temperature
    spreads it. Combined with entmax's exact sparsity, this makes the *number* of
    attended snippets a learned, per-video quantity rather than a fixed K.
    """

    def __init__(self, d_model: int, attn: str = "entmax",
                 adaptive: bool = True, fixed_temp: float = 1.0):
        super().__init__()
        self.attn_fn = ATTN_FNS[attn]
        self.adaptive = adaptive
        self.fixed_temp = fixed_temp
        self.score = nn.Sequential(
            nn.Linear(d_model, d_model // 2), nn.Tanh(), nn.Linear(d_model // 2, 1))
        if adaptive:
            # Predicts log-temperature from pooled context; bounded to keep it stable.
            self.budget_gate = nn.Sequential(
                nn.Linear(d_model, d_model // 4), nn.ReLU(inplace=True),
                nn.Linear(d_model // 4, 1), nn.Tanh())

    def forward(self, h: torch.Tensor, mask: Optional[torch.Tensor] = None):
        """
        h: [B,T,D], mask: [B,T]
        returns (context [B,D], weights [B,T], temperature [B,1])
        """
        B, T, D = h.shape
        logits = self.score(h).squeeze(-1)                     # [B,T]

        if mask is not None:
            denom = mask.sum(dim=1, keepdim=True).clamp(min=1).to(h.dtype)
            pooled = (h * mask.unsqueeze(-1).to(h.dtype)).sum(dim=1) / denom
        else:
            pooled = h.mean(dim=1)

        if self.adaptive:
            # tanh output in (-1,1) -> temperature in (e^-1.5, e^1.5) ~ (0.22, 4.5)
            temp = torch.exp(1.5 * self.budget_gate(pooled))   # [B,1]
        else:
            temp = torch.full((B, 1), self.fixed_temp, device=h.device, dtype=h.dtype)

        logits = logits / temp.clamp(min=1e-3)
        if mask is not None:
            logits = logits.masked_fill(~mask, NEG_MASK)
        w = self.attn_fn(logits, dim=1)                        # [B,T], exactly sparse
        if mask is not None:
            w = w * mask.to(w.dtype)
        ctx = torch.bmm(w.unsqueeze(1), h).squeeze(1)          # [B,D]
        return ctx, w, temp


# ---------------------------------------------------------------------------
# The model
# ---------------------------------------------------------------------------
class ATAHS(nn.Module):
    """
    Adaptive Temporal Attention with Hybrid Scoring.

    Ablation switches (each isolates one claim in the paper):
        use_multiscale=False   removes dilated temporal context
        adaptive_budget=False  fixed sparsity instead of per-video budget
        attn="softmax"         dense attention instead of exactly-sparse
        heads=("mil",)         single-head scoring instead of the hybrid
        adaptive_fusion=False  fixed equal weights instead of learned gating
    """

    def __init__(
        self,
        in_dim: int,
        d_model: int = 512,
        dropout: float = 0.3,
        attn: str = "entmax",
        use_multiscale: bool = True,
        adaptive_budget: bool = True,
        heads: Tuple[str, ...] = ("mil", "mag", "tmp"),
        adaptive_fusion: bool = True,
        fixed_temp: float = 1.0,
    ):
        super().__init__()
        self.heads = tuple(heads)
        self.adaptive_fusion = adaptive_fusion
        self.use_multiscale = use_multiscale

        self.embed = nn.Sequential(
            nn.Linear(in_dim, d_model), nn.LayerNorm(d_model),
            nn.ReLU(inplace=True), nn.Dropout(dropout))
        self.temporal = MultiScaleTemporal(d_model, dropout=dropout) if use_multiscale else None
        self.attn = AdaptiveTemporalAttention(d_model, attn=attn, adaptive=adaptive_budget,
                                              fixed_temp=fixed_temp)

        # Head 1: supervised MIL score per snippet.
        self.mil_head = nn.Sequential(
            nn.Linear(d_model, 128), nn.ReLU(inplace=True), nn.Dropout(dropout),
            nn.Linear(128, 1))
        # Head 2: deviation from a learned "normal" centre (one-class signal).
        self.normal_centre = nn.Parameter(torch.zeros(d_model))
        self.mag_scale = nn.Parameter(torch.tensor(1.0))
        # Head 3: predict the next snippet's embedding; error is the score.
        self.predictor = nn.Sequential(
            nn.Linear(d_model, d_model), nn.ReLU(inplace=True), nn.Linear(d_model, d_model))
        # Fusion gate over the active heads.
        if adaptive_fusion and len(self.heads) > 1:
            self.fusion_gate = nn.Sequential(
                nn.Linear(d_model, 64), nn.ReLU(inplace=True), nn.Linear(64, len(self.heads)))

    # -- individual score heads -------------------------------------------
    @staticmethod
    def _masked_mean(v: torch.Tensor, mask: Optional[torch.Tensor]) -> torch.Tensor:
        """
        Mean over real positions only.

        The magnitude and prediction heads centre their scores on the bag mean.
        Taking that mean over padded positions too would make a snippet's score
        depend on how much padding happened to be in its batch -- and since
        training batches are heavily padded while inference runs one unpadded
        video at a time, the model would be normalised differently at test time
        than it was trained. That silently costs far more accuracy than it looks
        like it should.
        """
        if mask is None:
            return v.mean(dim=1, keepdim=True)
        m = mask.to(v.dtype)
        return (v * m).sum(dim=1, keepdim=True) / m.sum(dim=1, keepdim=True).clamp(min=1)

    def _score_mil(self, h):
        return torch.sigmoid(self.mil_head(h)).squeeze(-1)

    def _score_mag(self, h, mask=None):
        d = torch.norm(h - self.normal_centre, dim=-1)         # [B,T]
        return torch.sigmoid(self.mag_scale * (d - self._masked_mean(d, mask)))

    def _score_tmp(self, h, mask=None):
        pred = self.predictor(h[:, :-1])                       # predict t+1 from t
        err = torch.norm(pred - h[:, 1:].detach(), dim=-1)     # [B,T-1]
        err = F.pad(err, (1, 0), value=0.0)                    # align to [B,T]
        return torch.sigmoid(err - self._masked_mean(err, mask)), pred

    def forward(self, x: torch.Tensor, mask: Optional[torch.Tensor] = None) -> Dict[str, torch.Tensor]:
        h = self.embed(x)
        if self.temporal is not None:
            h = self.temporal(h, mask)
        ctx, w, temp = self.attn(h, mask)

        parts, pred = {}, None
        if "mil" in self.heads:
            parts["mil"] = self._score_mil(h)
        if "mag" in self.heads:
            parts["mag"] = self._score_mag(h, mask)
        if "tmp" in self.heads:
            parts["tmp"], pred = self._score_tmp(h, mask)

        stack = torch.stack([parts[k] for k in self.heads], dim=-1)   # [B,T,H]
        if self.adaptive_fusion and len(self.heads) > 1:
            gate = torch.softmax(self.fusion_gate(h), dim=-1)         # [B,T,H]
            score = (stack * gate).sum(dim=-1)
        else:
            gate = torch.full_like(stack, 1.0 / len(self.heads))
            score = stack.mean(dim=-1)

        if mask is not None:
            score = score.masked_fill(~mask, 0.0)
        return {"score": score, "attn": w, "temp": temp, "embed": h,
                "context": ctx, "parts": parts, "gate": gate, "pred": pred}


# ---------------------------------------------------------------------------
# Objective
# ---------------------------------------------------------------------------
def topk_mean(scores: torch.Tensor, mask: Optional[torch.Tensor], k_ratio: float = 0.1,
              k_fixed: int = 0) -> torch.Tensor:
    """
    Mean of the top-k snippet scores per bag.

    More robust than the single max used by Sultani et al.: one noisy snippet
    cannot carry a whole bag, which matters on untrimmed real-world video.

    ``k_fixed > 0`` uses an absolute k; otherwise k = round(k_ratio * T).

    Prefer a small absolute k. UCF-Crime's positive frame rate is only ~7.6%, so
    a proportional k over-selects: a 112-snippet video holds roughly 8 anomalous
    snippets, and k_ratio=0.1 averages 11 scores -- dragging normal snippets into
    the positive bag score and blunting the ranking signal. RTFM and its
    successors use a small fixed k for exactly this reason.
    """
    B, T = scores.shape
    s = scores.masked_fill(~mask, float("-inf")) if mask is not None else scores
    lengths = mask.sum(dim=1) if mask is not None else torch.full((B,), T, device=scores.device)
    out = []
    for i in range(B):
        n = int(lengths[i].item())
        k = k_fixed if k_fixed > 0 else max(1, int(round(k_ratio * n)))
        out.append(s[i, :n].topk(min(max(k, 1), n)).values.mean())
    return torch.stack(out)


def atahs_loss(
    out: Dict[str, torch.Tensor],
    labels: torch.Tensor,
    mask: Optional[torch.Tensor] = None,
    k_ratio: float = 0.1,
    k_fixed: int = 0,
    lambda_smooth: float = 8e-4,
    lambda_sparse: float = 8e-4,
    lambda_budget: float = 1e-3,
    lambda_mag: float = 1e-2,
    lambda_pred: float = 1e-2,
) -> Tuple[torch.Tensor, Dict[str, float]]:
    """
    Composite objective.

    rank    top-k-mean MIL hinge between anomalous and normal bags
    smooth  temporal smoothness of the score on anomalous bags
    sparse  score sparsity on anomalous bags (anomalies are rare)
    budget  attention concentration -- pays for spending attention mass broadly,
            which is what makes the per-video budget adaptive rather than free
    mag     pulls normal-bag embeddings toward the learned normal centre
    pred    next-snippet prediction error on NORMAL bags only, so the temporal
            head learns what "normal" looks like and reports error on anomalies
    """
    scores, w = out["score"], out["attn"]
    pos, neg = labels > 0.5, labels <= 0.5
    if not pos.any() or not neg.any():
        raise ValueError("batch must contain both anomalous and normal bags")

    bag = topk_mean(scores, mask, k_ratio, k_fixed)
    rank = F.relu(1.0 - bag[pos].unsqueeze(1) + bag[neg].unsqueeze(0)).mean()

    m = mask.float() if mask is not None else torch.ones_like(scores)
    s_pos, m_pos = scores[pos], m[pos]
    pair = (m_pos[:, 1:] * m_pos[:, :-1])
    smooth = (((s_pos[:, 1:] - s_pos[:, :-1]) ** 2) * pair).sum(1).mean()
    sparse = (s_pos * m_pos).sum(1).mean()

    # Attention entropy: low = concentrated. Penalising it makes the gate earn
    # every snippet it keeps, so K(v) stays small unless the video needs it.
    ent = -(w.clamp(min=1e-8).log() * w).sum(dim=1).mean()

    total = rank + lambda_smooth * smooth + lambda_sparse * sparse + lambda_budget * ent
    stats = {"rank": float(rank.detach()), "smooth": float(smooth.detach()),
             "sparse": float(sparse.detach()), "attn_entropy": float(ent.detach())}

    h = out["embed"]
    if "mag" in out["parts"]:
        # Compactness on normal bags only -- the one-class part of the hybrid.
        h_neg, m_neg = h[neg], m[neg]
        dist = torch.norm(h_neg - h_neg.new_zeros(1), dim=-1)
        mag = ((dist * m_neg).sum(1) / m_neg.sum(1).clamp(min=1)).mean()
        total = total + lambda_mag * mag
        stats["mag"] = float(mag.detach())

    if out.get("pred") is not None:
        pred, tgt = out["pred"][neg], h[neg][:, 1:].detach()
        pm = m[neg][:, 1:]
        perr = ((((pred - tgt) ** 2).mean(-1)) * pm).sum(1) / pm.sum(1).clamp(min=1)
        perr = perr.mean()
        total = total + lambda_pred * perr
        stats["pred"] = float(perr.detach())

    stats["total"] = float(total.detach())
    # Mean fraction of snippets receiving non-zero attention -- the realised K(v)/T.
    stats["attn_density"] = float((w > 1e-6).float().sum(1).mean().detach())
    return total, stats
